export function IconStar({ size = 20, className = "", style = {}, fillPct = 0, color }) {
  const resolvedColor = color || style?.color || "currentColor";
  const isFilled = fillPct > 0;
  const isFull = fillPct >= 99;
  const gradId = `star-grad-${Math.floor(fillPct)}-${Math.floor(Math.random() * 10000)}`;

  return (
    <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke={resolvedColor} strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" className={className} style={style}>
      {isFilled && !isFull && (
        <defs>
          <linearGradient id={gradId} x1="0%" y1="0%" x2="100%" y2="0%">
            <stop offset={`${fillPct}%`} stopColor={resolvedColor} />
            <stop offset={`${fillPct}%`} stopColor="transparent" />
          </linearGradient>
        </defs>
      )}
      <polygon points="12 2 15.09 8.26 22 9.27 17 14.14 18.18 21.02 12 17.77 5.82 21.02 7 14.14 2 9.27 8.91 8.26 12 2" fill={isFull ? resolvedColor : isFilled ? `url(#${gradId})` : "none"} />
    </svg>
  );
}

